"""Purchase Order Generation Agent — turns decisions into structured, approvable POs (and PDFs)."""
import pandas as pd
from fpdf import FPDF
from config import AUTO_APPROVE_LIMIT

PRIORITY = {"CRITICAL": "Urgent", "HIGH": "High", "MEDIUM": "Normal", "LOW": "Normal"}


class POAgent:
    name = "PO Agent"

    def __init__(self, data):
        self.products = data["products"].set_index("product_id")
        self.vendors = data["vendors"].set_index("vendor_id")
        self.warehouses = data["warehouses"].set_index("warehouse_id")

    def create(self, today, n, row, best, qty, reason, options):
        po_id = f"AI-{today:%y%m%d}-{row.warehouse_id[-3:]}-{row.product_id}"   # unique per item per day
        total = round(best["unit_price"] * qty, 2)
        return dict(
            po_id=po_id, order_date=today.date(), warehouse_id=row.warehouse_id, product_id=row.product_id,
            product_name=row.product_name, vendor_id=best["vendor_id"], vendor_name=best["vendor_name"],
            qty=int(qty), unit_price=best["unit_price"], total_cost=total,
            expected_delivery=(today + pd.Timedelta(days=int(best["promised_lead"]))).date(),
            expected_lead_days=best["expected_lead"], priority=PRIORITY.get(row.risk, "Normal"), risk=row.risk,
            days_to_stockout=row.days_to_stockout, reason=reason, needs_human=total >= AUTO_APPROVE_LIMIT,
            status="Pending approval", options=options,
        )

    def to_pdf(self, po: dict) -> bytes:
        v = self.vendors.loc[po["vendor_id"]]
        w = self.warehouses.loc[po["warehouse_id"]]
        pdf = FPDF()
        pdf.add_page()
        pdf.set_font("Helvetica", "B", 18)
        pdf.cell(0, 12, "PURCHASE ORDER", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(0, 6, "Sahyadri Retail Distribution  |  Generated by Supply Chain AI Agent", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(4)
        def line(k, val):
            pdf.set_font("Helvetica", "B", 10); pdf.cell(45, 7, k)
            pdf.set_font("Helvetica", "", 10); pdf.cell(0, 7, str(val), new_x="LMARGIN", new_y="NEXT")
        line("PO number", po["po_id"]); line("Order date", po["order_date"])
        line("Priority", po["priority"]); line("Vendor", f"{v.vendor_name} ({po['vendor_id']}), {v.city}")
        line("Deliver to", f"{w.warehouse_name}, {w.city}")
        line("Expected delivery", po["expected_delivery"]); line("Payment terms", f"{v.payment_terms_days} days")
        pdf.ln(4)
        pdf.set_font("Helvetica", "B", 10); pdf.set_fill_color(230, 233, 228)
        for h, wd in [("Product", 80), ("Qty", 25), ("Unit price (Rs)", 40), ("Amount (Rs)", 40)]:
            pdf.cell(wd, 8, h, border=1, fill=True)
        pdf.ln()
        pdf.set_font("Helvetica", "", 10)
        pdf.cell(80, 8, po["product_name"], border=1); pdf.cell(25, 8, str(po["qty"]), border=1)
        pdf.cell(40, 8, f"{po['unit_price']:,.2f}", border=1); pdf.cell(40, 8, f"{po['total_cost']:,.2f}", border=1)
        pdf.ln(14)
        pdf.set_font("Helvetica", "B", 10); pdf.cell(0, 6, "Why this order was raised", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 10)
        text = po["reason"].replace("₹", "Rs ").replace("—", "-").replace("·", "|").replace("→", "->")
        pdf.multi_cell(0, 6, text.encode("latin-1", "replace").decode("latin-1"))
        pdf.ln(10)
        pdf.cell(0, 6, f"Status: {po['status']}", new_x="LMARGIN", new_y="NEXT")
        pdf.cell(0, 6, "Authorised signatory: ____________________", new_x="LMARGIN", new_y="NEXT")
        return bytes(pdf.output())
